# ─── Registro de actividad (Firestore) ────────────────────────────────────────
# Proyecto: alchomes-mobile. Credencial ya configurada en Render como
# FIRESTORE_CREDENTIALS_JSON (JSON de cuenta de servicio, como texto plano).
# Todo el logging está envuelto en try/except: si Firestore falla o no está
# configurado, la app sigue funcionando con Beds24 con total normalidad —
# el registro de auditoría nunca debe poder romper una reserva o un bloqueo.
_firestore_client = None
_firestore_init_attempted = False


def _get_firestore_client():
    global _firestore_client, _firestore_init_attempted
    if _firestore_client is not None:
        return _firestore_client
    if _firestore_init_attempted:
        return None  # ya se intentó antes y falló; no reintentar en cada request
    _firestore_init_attempted = True
    try:
        from google.cloud import firestore
        from google.oauth2 import service_account

        raw = os.environ.get("FIRESTORE_CREDENTIALS_JSON")
        if not raw:
            return None
        info = json.loads(raw)
        creds = service_account.Credentials.from_service_account_info(info)
        project_id = info.get("project_id", "alchomes-mobile")
        _firestore_client = firestore.Client(credentials=creds, project=project_id)
        return _firestore_client
    except Exception as e:
        print(f"[firestore] no se pudo inicializar: {e}")
        return None


def log_action(user_name, device_id, action, details=None):
    """
    Registra una acción en Firestore (colección 'activity_log').
    Nunca lanza excepción hacia arriba: un fallo aquí no debe afectar
    a la operación real contra Beds24 que ya se ha completado.
    """
    try:
        db = _get_firestore_client()
        if db is None:
            return
        db.collection("activity_log").add({
            "timestamp":  datetime.utcnow().isoformat(),
            "userName":   (user_name or "Desconocido").strip()[:80],
            "deviceId":   (device_id or "")[:80],
            "userAgent":  request.headers.get("User-Agent", "")[:300],
            "action":     action,
            "details":    details or {},
        })
    except Exception as e:
        print(f"[firestore] error al registrar acción: {e}")


# ─── Mantenimiento de tokens Beds24 (evitar caducidad por inactividad) ────────
# Según la documentación de Beds24: "Refresh tokens do not expire so long as
# they have been used within the past 30 days." — es decir, NO caducan en una
# fecha fija; caducan solo si pasan 30 días sin usarse. Manteniéndolos "vivos"
# con una llamada periódica a /authentication/token, nunca deberían caducar.
#
# Variables de entorno usadas (ya configuradas en Render):
#   CALLMEBOT_PHONE_1 / CALLMEBOT_APIKEY_1  -> aviso WhatsApp nº1
#   CALLMEBOT_PHONE_2 / CALLMEBOT_APIKEY_2  -> aviso WhatsApp nº2
#   MOBILE_BEDS24_TOKEN                     -> token de la app (este blueprint)
#   BEDS24_REFRESH_TOKEN                    -> token principal (otros procesos)

TOKEN_WARNING_DAYS = 23   # avisar cuando lleven >=23 días sin usarse (~1 semana antes del límite de 30)
KEEPALIVE_INTERVAL_HOURS = 20  # no comprobar en cada ping de UptimeRobot, solo ~1 vez al día


def _send_whatsapp(text):
    """Envía un aviso de WhatsApp a los dos números configurados vía CallMeBot."""
    for i in (1, 2):
        phone = os.environ.get(f"CALLMEBOT_PHONE_{i}")
        apikey = os.environ.get(f"CALLMEBOT_APIKEY_{i}")
        if not phone or not apikey:
            continue
        try:
            requests.get(
                "https://api.callmebot.com/whatsapp.php",
                params={"phone": phone, "text": text, "apikey": apikey},
                timeout=15,
            )
        except Exception as e:
            print(f"[whatsapp] error enviando a {phone}: {e}")


def _try_refresh_token(refresh_token):
    """Intenta usar un refresh token contra Beds24. Devuelve True si funcionó."""
    if not refresh_token:
        return None  # no configurado, no aplica
    try:
        resp = requests.get(
            f"{BEDS24_API}/authentication/token",
            headers={"accept": "application/json", "refreshToken": refresh_token},
            timeout=15,
        )
        return resp.ok
    except Exception:
        return False


def _token_health_doc():
    db = _get_firestore_client()
    if db is None:
        return None
    return db.collection("system_state").document("token_health")


def check_and_maintain_tokens():
    """
    Se llama desde /health (que UptimeRobot pinga cada 5 min).
    Como mucho una vez cada KEEPALIVE_INTERVAL_HOURS:
      1. Usa ambos refresh tokens contra Beds24 para que no cuenten como
         "inactivos" (esto es lo que realmente evita que caduquen).
      2. Si alguno lleva demasiados días sin usarse con éxito, o si el
         intento de hoy falla, avisa por WhatsApp (máximo 1 vez al día).
    Todo el bloque está protegido: si Firestore no está disponible, esta
    función simplemente no hace nada — nunca debe romper /health.
    """
    doc_ref = _token_health_doc()
    if doc_ref is None:
        return
    try:
        snap = doc_ref.get()
        state = snap.to_dict() if snap.exists else {}
        now = datetime.utcnow()

        last_check = state.get("last_keepalive_check")
        if last_check:
            try:
                last_check_dt = datetime.fromisoformat(last_check)
                if (now - last_check_dt).total_seconds() < KEEPALIVE_INTERVAL_HOURS * 3600:
                    return  # aún no toca comprobar
            except Exception:
                pass

        mobile_token = os.environ.get("MOBILE_BEDS24_TOKEN")
        main_token = os.environ.get("BEDS24_REFRESH_TOKEN")

        mobile_ok = _try_refresh_token(mobile_token)
        main_ok = _try_refresh_token(main_token) if main_token != mobile_token else mobile_ok

        if mobile_ok:
            state["mobile_last_refresh"] = now.isoformat()
        if main_ok:
            state["main_last_refresh"] = now.isoformat()
        state.setdefault("mobile_last_refresh", now.isoformat())
        state.setdefault("main_last_refresh", now.isoformat())
        state["last_keepalive_check"] = now.isoformat()

        def days_since(iso):
            try:
                return (now - datetime.fromisoformat(iso)).days
            except Exception:
                return 0

        mobile_days = days_since(state["mobile_last_refresh"])
        main_days = days_since(state["main_last_refresh"])

        problems = []
        if mobile_ok is False:
            problems.append("⚠️ El token MOBILE_BEDS24_TOKEN ha fallado al renovarse hoy.")
        elif mobile_days >= TOKEN_WARNING_DAYS:
            problems.append(f"⏰ El token MOBILE_BEDS24_TOKEN lleva {mobile_days} días sin renovarse (caduca a los 30 días de inactividad).")
        if main_token and main_ok is False:
            problems.append("⚠️ El token BEDS24_REFRESH_TOKEN ha fallado al renovarse hoy.")
        elif main_token and main_days >= TOKEN_WARNING_DAYS:
            problems.append(f"⏰ El token BEDS24_REFRESH_TOKEN lleva {main_days} días sin renovarse (caduca a los 30 días de inactividad).")

        if problems:
            last_alert = state.get("last_alert_sent")
            today_str = now.strftime("%Y-%m-%d")
            if last_alert != today_str:
                msg = "🏨 Alchomes — Aviso de tokens Beds24\n\n" + "\n".join(problems) + \
                      "\n\nRevisa el panel de la app o regenera el token en Beds24 cuanto antes."
                _send_whatsapp(msg)
                state["last_alert_sent"] = today_str

        doc_ref.set(state)
    except Exception as e:
        print(f"[token-health] error: {e}")


