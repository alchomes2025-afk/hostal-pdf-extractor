def _parse_bookings_list(raw, include_cancelled=False):
    """
    Convierte lista cruda de Beds24 al formato de la app.

    include_cancelled=True → conserva las reservas canceladas en el resultado
    (necesario en /check-changes para poder ELIMINARLAS del estado; si se
    filtran aquí, la cancelación nunca llega a la lógica de fusión — ese era
    el bug por el que reservas canceladas seguían apareciendo en la app).
    """
    result = []
    for b in (raw or []):
        if not include_cancelled and str(b.get("status", "")).lower() == "cancelled":
            continue
        arrival   = (b.get("arrival",   "") or "")[:10]
        departure = (b.get("departure", "") or "")[:10]
        if not arrival or not departure:
            continue
        guest = b.get("guest") or {}
        first = guest.get("firstName") or b.get("guestFirstName") or b.get("firstName") or ""
        last  = guest.get("lastName")  or b.get("guestLastName")  or b.get("lastName")  or ""
        phone = guest.get("phone") or guest.get("mobile") or b.get("guestPhone") or b.get("phone") or ""
        email = guest.get("email") or b.get("guestEmail") or b.get("email") or ""
        result.append({
            "id":        b.get("id"),          # ID de Beds24 (necesario para cancelar)
            "roomId":    b.get("roomId"),
            "arrival":   arrival,
            "departure": departure,
            "guestName": f"{first} {last}".strip() or "Huésped",
            "phone":     phone,
            "email":     email,
            "status":    b.get("status"),
        })
    return result


def _load_bookings():
    """
    Carga TODOS los bookings de TODAS las propiedades (PROPERTY_IDS).

    Estrategia de llamadas a Beds24 (v9 — corregido; v10 — multi-propiedad):
    · Beds24 devuelve resultados INCOMPLETOS cuando el rango arrivalFrom→arrivalTo
      es muy amplio (545 días: 180 atrás + 365 adelante) en una sola llamada —
      confirmado comparando contra una consulta de 60 días, que sí trae todo.
      No es un error HTTP, simplemente omite reservas silenciosamente.
    · Fix: se pide en trozos de ~60 días (igual que /debug-bookings, que es fiable)
      y se combinan los resultados, sin pasarnos nunca de un rango ancho por llamada.
    · Se repite la misma consulta por trozos para cada propertyId de PROPERTY_IDS
      (el id de reserva de Beds24 es único en toda la cuenta, así que seen_ids
      sigue siendo válido como set global entre propiedades).
    · Esta función solo se ejecuta al arrancar el servidor o en /reload.
    """
    token = get_access_token()
    today = date.today()
    window_from = today - timedelta(days=180)
    window_to   = today + timedelta(days=365)

    CHUNK_DAYS = 60
    all_raw = []
    seen_ids = set()

    for property_id in PROPERTY_IDS:
        chunk_start = window_from
        while chunk_start <= window_to:
            chunk_end = min(chunk_start + timedelta(days=CHUNK_DAYS), window_to)
            params_base = {
                "propertyId":          property_id,
                "arrivalFrom":         chunk_start.strftime("%Y-%m-%d"),
                "arrivalTo":           chunk_end.strftime("%Y-%m-%d"),
                "includePersonalInfo": "true",
                "limit":               500,
            }

            page = 1
            while True:
                resp = b24_get(token, "/bookings", params={**params_base, "page": page})
                if not resp.ok:
                    break  # este trozo falló; seguimos con el resto en vez de abortar todo
                data = resp.json().get("data") or []
                for b in data:
                    bid = b.get("id")
                    if bid is not None and bid in seen_ids:
                        continue  # evitar duplicados en los bordes de cada trozo
                    if bid is not None:
                        seen_ids.add(bid)
                    all_raw.append(b)
                if len(data) < 500:
                    break
                page += 1
                if page > 10:
                    break

            chunk_start = chunk_end + timedelta(days=1)

    _state["bookings"]   = _parse_bookings_list(all_raw)
    _state["overrides"]  = _load_overrides_from_firestore()  # precios editados manualmente, guardados por nosotros
    _state["loaded_at"]  = datetime.utcnow().isoformat()
    _state["checked_at"] = datetime.utcnow().isoformat()
    _state["loaded"]     = True


def _load_overrides(token=None):
    """
    [SOLO DIAGNÓSTICO — ya no se usa para el funcionamiento real de la app]

    Intento de cargar overrides desde Beds24 vía GET /inventory/rooms/calendar.
    Probado en vivo (ver /debug-overrides?probe=1) con varias combinaciones de
    parámetros de fecha, y siempre devuelve el calendario vacío para esta
    cuenta, aunque existan overrides reales guardados momentos antes. Por eso
    la app usa _load_overrides_from_firestore() como fuente real. Esta función
    se conserva solo para que /debug-overrides pueda seguir comparando ambas
    fuentes, por si Beds24 cambia el comportamiento de este endpoint más adelante.
    """
    if token is None:
        token = get_access_token()
    today = date.today()
    window_from = (today - timedelta(days=30)).strftime("%Y-%m-%d")
    window_to   = (today + timedelta(days=365)).strftime("%Y-%m-%d")

    overrides = {}
    for room in ROOMS:
        room_id = room["id"]
        rid_str = str(room_id)
        try:
            resp = b24_get(token, "/inventory/rooms/calendar", params={
                "roomId":    room_id,
                "startDate": window_from,
                "endDate":   window_to,
            })
            if not resp.ok:
                print(f"[overrides] GET calendar habitación {room_id} falló: {resp.status_code} {resp.text[:200]}")
                continue
            data = resp.json().get("data") or []
            # La respuesta puede venir como [{roomId, calendar:[{date/from, price1, numAvail}, ...]}]
            # o, en algunas cuentas, como una lista plana de días por habitación.
            # Se contemplan ambas formas para no depender de un único formato.
            for entry in data:
                cal = entry.get("calendar") if isinstance(entry, dict) else None
                day_list = cal if cal is not None else [entry]
                for day in day_list:
                    if not isinstance(day, dict):
                        continue
                    ds = day.get("date") or day.get("from")
                    if not ds:
                        continue
                    o = {}
                    if day.get("price1") is not None:
                        o["price1"] = day["price1"]
                    if day.get("numAvail") is not None:
                        o["numAvail"] = day["numAvail"]
                    if o:
                        overrides.setdefault(rid_str, {})[ds] = o
        except Exception as e:
            print(f"[overrides] error cargando habitación {room_id}: {e}")

    return overrides


